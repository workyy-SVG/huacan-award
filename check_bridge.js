const fs=require('node:fs'), vm=require('node:vm'), assert=require('node:assert/strict');
const html=fs.readFileSync(__dirname+'/qwen-component/index.html','utf8');
const handlers={}, sent=[], delivered=[], timers=new Map(), storage=new Map(); let n=0;
const parent={innerHeight:800,postMessage:m=>sent.push(m)};
const site={contentWindow:{postMessage:m=>delivered.push(m)}};
const ctx={document:{getElementById:()=>site},parent,sessionStorage:{setItem:(k,v)=>storage.set(k,v)},addEventListener:(t,f)=>handlers[t]=f,setTimeout:f=>{timers.set(++n,f);return n},clearTimeout:i=>timers.delete(i)};
vm.runInNewContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],ctx);
const send=data=>handlers.message({source:site.contentWindow,data});
handlers.message({source:parent,data:{type:'streamlit:render',args:{html:'test',site_key:'one'}}});
send({type:'zili-ready'});
send({type:'qwen-request',request:{id:'first'}});
send({type:'qwen-request',request:{id:'second'}});
assert.match(delivered.at(-1).error,/上一个/);
for(const f of [...timers.values()])f();
assert.match(delivered.at(-1).error,/超时/);
send({type:'qwen-request',request:{id:'retry'}});
assert.equal(sent.filter(m=>m.type==='streamlit:setComponentValue').length,2);
send({type:'qwen-cancel',id:'retry'});
send({type:'qwen-request',request:{id:'after-cancel'}});
assert.equal(sent.filter(m=>m.type==='streamlit:setComponentValue').length,3);
handlers.message({source:parent,data:{type:'streamlit:render',args:{html:'test',site_key:'one',response:{id:'after-cancel',text:'回答'}}}});
assert.equal(delivered.at(-1).text,'回答');
vm.runInNewContext(require('node:zlib').gunzipSync(Buffer.from(fs.readFileSync(__dirname+'/opencc-full.gz.b64','utf8'),'base64')).toString('utf8'),ctx);
assert.equal(vm.runInNewContext("OpenCC.Converter({from:'cn',to:'tw'})('精选寻踪 点击 团圆 台湾')",ctx),'精選尋蹤 點擊 團圓 臺灣');
console.log('PASS: explicit busy response, timeout recovery, cancellation, response delivery, OpenCC conversion');
const existing=site.srcdoc;
handlers.message({source:parent,data:{type:'streamlit:render',args:{html:'',site_key:'one'}}});
assert.equal(site.srcdoc,existing,'audio-only render must preserve the live site');
ctx.crypto={randomUUID:()=> 'bootstrap-id'};
handlers.message({source:parent,data:{type:'streamlit:render',args:{html:'',site_key:'new-version'}}});
assert.equal(sent.at(-1).value.mode,'bootstrap');
const sentCount=sent.length;
handlers.message({source:parent,data:{type:'streamlit:render',args:{html:'',site_key:'new-version'}}});
assert.equal(sent.length,sentCount,'only request one bootstrap while waiting');
handlers.message({source:parent,data:{type:'streamlit:render',args:{html:'new HTML',site_key:'new-version'}}});
assert.equal(site.srcdoc,'new HTML');
console.log('PASS: lightweight rerenders retain the page; fresh/reconnected clients recover their HTML');
